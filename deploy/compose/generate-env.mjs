// Writes deploy/compose/.env with fresh random secrets for the docker compose stack.
//
//   node deploy/compose/generate-env.mjs            create .env (refuses to overwrite)
//   node deploy/compose/generate-env.mjs --force    replace it (stored credentials become unreadable!)
//
// The file is git-ignored. Never commit it: it holds the vault encryption key, the signing
// secrets and the database passwords. The script prints key ids, never secrets.
import { createHash, generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = resolve(dirname(fileURLToPath(import.meta.url)), '.env');
if (existsSync(out) && !process.argv.includes('--force')) {
  console.error(`[compose] ${out} already exists. Keep it: VAULT_ENCRYPTION_KEY decrypts the stored credentials.`);
  console.error('[compose] To start over with empty volumes: docker compose down -v, then run again with --force.');
  process.exit(1);
}

const secret = () => randomBytes(32).toString('base64url');
const escape = (pem) => pem.trim().replace(/\n/g, '\\n');
const cms = generateKeyPairSync('ed25519');
const pub = cms.publicKey.export({ type: 'spki', format: 'pem' }).toString();
const cmsKeyId = createHash('sha256').update(cms.publicKey.export({ type: 'spki', format: 'der' })).digest('hex').slice(0, 16);

const lines = [
  '# Generated by deploy/compose/generate-env.mjs. Secrets: never commit, never share.',
  '',
  '# Images (build locally with `docker compose build`, or point REGISTRY/TAG at your registry)',
  'REGISTRY=token-vault',
  'TAG=dev',
  '',
  '# Public URLs (what browsers use; also the OAuth redirect base)',
  'CONSOLE_PUBLIC_URL=http://localhost:8080',
  '',
  '# PostgreSQL: superuser (bootstrap only) and one role per service',
  `POSTGRES_PASSWORD=${secret()}`,
  `CONTROL_PLANE_DB_PASSWORD=${secret()}`,
  `WEBHOOK_DB_PASSWORD=${secret()}`,
  `CMS_DB_PASSWORD=${secret()}`,
  '',
  '# Control plane <-> customer webhook request signing (shared; rotate with the documented steps)',
  `WEBHOOK_SIGNING_SECRET=${secret()}`,
  'WEBHOOK_PREVIOUS_SIGNING_SECRETS=',
  '# Control plane audit-chain signatures',
  `AUDIT_SIGNING_KEY=${secret()}`,
  '',
  '# Customer webhook credential encryption (AES-256). Losing it makes stored credentials unreadable.',
  `VAULT_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
  'VAULT_PREVIOUS_ENCRYPTION_KEYS=',
  '# Dev Vault root token, used only by the vault-transit.yml override (try the webhook with a KMS)',
  `VAULT_DEV_TOKEN=${secret()}`,
  '# mock = simulated providers; live = real APIs (PROVIDER_MODES=github=live,... per application)',
  'UPSTREAM_MODE=mock',
  'PROVIDER_MODES=',
  '',
  '# Provider CMS: Ed25519 signing key (CMS only) and its public key (pinned by the control plane and the webhook)',
  `CMS_SIGNING_PRIVATE_KEY=${escape(cms.privateKey.export({ type: 'pkcs8', format: 'pem' }).toString())}`,
  `CMS_PUBLIC_KEY=${escape(pub)}`,
  '# Signs CMS sign-in sessions (JWT); required in production',
  `CMS_JWT_SECRET=${secret()}`,
  '# Set to false to require a second person for every publication',
  'CMS_ADMIN_DIRECT_PUBLISH=true',
  '',
];
writeFileSync(out, lines.join('\n'), { mode: 0o600 });
console.log(`[compose] wrote ${out} (mode 600). CMS signing key id ${cmsKeyId}.`);
console.log('[compose] Next: docker compose -f deploy/compose/docker-compose.yml up -d --build');
