// Generates per-process .env files with random development secrets.
// Secrets are never committed (see .gitignore). Existing files are left untouched.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const serverEnv = resolve(root, 'server/.env');
const webhookEnv = resolve(root, 'webhook/.env');

function readVar(file, name) {
  if (!existsSync(file)) return undefined;
  const m = readFileSync(file, 'utf8').match(new RegExp(`^${name}=(.*)$`, 'm'));
  return m?.[1];
}

// The HMAC signing secret is the one value both trust zones share (by design, for the local POC).
const signing =
  readVar(serverEnv, 'WEBHOOK_SIGNING_SECRET') ??
  readVar(webhookEnv, 'WEBHOOK_SIGNING_SECRET') ??
  randomBytes(32).toString('base64url');

if (!existsSync(serverEnv)) {
  writeFileSync(
    serverEnv,
    [
      '# Token Vault control plane (generated by scripts/setup.mjs; do not commit)',
      'PORT=4000',
      `WEBHOOK_SIGNING_SECRET=${signing}`,
      'DEFAULT_WEBHOOK_URL=http://localhost:4100',
      'HEARTBEAT_INTERVAL_MS=30000',
      '',
    ].join('\n'),
  );
  console.log('[setup] created server/.env');
}

if (!existsSync(webhookEnv)) {
  writeFileSync(
    webhookEnv,
    [
      '# Customer webhook / vault runtime (generated by scripts/setup.mjs; do not commit)',
      '# This file belongs to the CUSTOMER trust zone. The encryption key never leaves it.',
      'PORT=4100',
      `WEBHOOK_SIGNING_SECRET=${signing}`,
      `VAULT_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
      'WEBHOOK_INSTANCE_ID=whi_local_customer_vault',
      '# mock = simulated GitHub provider (default). live = call api.github.com with the stored token.',
      'GITHUB_MODE=mock',
      '',
    ].join('\n'),
  );
  console.log('[setup] created webhook/.env');
}
