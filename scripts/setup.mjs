// Generates per-process .env files with random development secrets.
// Secrets are never committed (see .gitignore). Existing files are left untouched.
//
// Runtime-only mode: if WEBHOOK_SIGNING_SECRET and VAULT_ENCRYPTION_KEY are already set in the
// environment (CI, containers, a secret manager), nothing is written to disk.
import { createPrivateKey, createPublicKey, generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

if (process.env.WEBHOOK_SIGNING_SECRET && process.env.VAULT_ENCRYPTION_KEY) {
  console.log('[setup] secrets provided via environment; skipping .env generation');
  process.exit(0);
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Host port of the local database (docker-compose.yml). Set POSTGRES_PORT in the root .env (which
// docker compose also reads) when 5432 is taken, e.g. by a PostgreSQL installed on Windows.
const rootEnv = resolve(root, '.env');
const PG_PORT_SET = process.env.POSTGRES_PORT ?? (existsSync(rootEnv) ? readFileSync(rootEnv, 'utf8').match(/^POSTGRES_PORT=(.*)$/m)?.[1]?.trim() : undefined);
if (PG_PORT_SET !== undefined && !/^\d{2,5}$/.test(PG_PORT_SET)) {
  console.error(`[setup] POSTGRES_PORT must be a port number, got "${PG_PORT_SET}"`);
  process.exit(1);
}
const PG_PORT = PG_PORT_SET ?? '5432';
const DEFAULT_DATABASE_URL = `postgres://token_vault:token_vault@127.0.0.1:${PG_PORT}/token_vault`;
// Customer zone: separate database and role (see scripts/pg-init.sql).
const DEFAULT_WEBHOOK_DATABASE_URL = `postgres://token_vault_customer:token_vault_customer@127.0.0.1:${PG_PORT}/token_vault_customer`;
const serverEnv = resolve(root, 'server/.env');
const webhookEnv = resolve(root, 'webhook/.env');
const cmsEnv = resolve(root, 'cms/api/.env');
const DEFAULT_CMS_DATABASE_URL = `postgres://token_vault_cms:token_vault_cms@127.0.0.1:${PG_PORT}/token_vault_cms`;

function readVar(file, name) {
  if (!existsSync(file)) return undefined;
  const m = readFileSync(file, 'utf8').match(new RegExp(`^${name}=(.*)$`, 'm'));
  return m?.[1];
}

// The HMAC signing secret is the one value both trust zones share (by design, for the local POC).
const signing =
  readVar(serverEnv, 'WEBHOOK_SIGNING_SECRET') ??
  readVar(webhookEnv, 'WEBHOOK_SIGNING_SECRET') ??
  randomBytes(32).toString('base64url');

if (!existsSync(serverEnv)) {
  writeFileSync(
    serverEnv,
    [
      '# Token Vault control plane (generated by scripts/setup.mjs; do not commit)',
      'PORT=4000',
      `WEBHOOK_SIGNING_SECRET=${signing}`,
      '# Old signing secret during a rotation (npm run webhook:rotate-secret); empty otherwise.',
      'WEBHOOK_PREVIOUS_SIGNING_SECRETS=',
      '# HMAC key for the tamper-evident audit chain. Keep it outside the database.',
      `AUDIT_SIGNING_KEY=${randomBytes(32).toString('base64url')}`,
      'DEFAULT_WEBHOOK_URL=http://localhost:4100',
      '# Local Postgres from docker-compose.yml (npm run db:up). Development credentials only.',
      `DATABASE_URL=${DEFAULT_DATABASE_URL}`,
      'HEARTBEAT_INTERVAL_MS=30000',
      '',
    ].join('\n'),
  );
  console.log('[setup] created server/.env');
}

// Upgrade: sessions are JWTs signed with SESSION_JWT_SECRET (optional outside production).
if (existsSync(serverEnv) && !readVar(serverEnv, 'SESSION_JWT_SECRET')) {
  writeFileSync(serverEnv, readFileSync(serverEnv, 'utf8').trimEnd() + `\nSESSION_JWT_SECRET=${randomBytes(32).toString('base64url')}\n`);
  console.log('[setup] added SESSION_JWT_SECRET to server/.env');
}

// Upgrade: server/.env files created before the audit chain lack AUDIT_SIGNING_KEY.
if (existsSync(serverEnv) && !readVar(serverEnv, 'AUDIT_SIGNING_KEY')) {
  writeFileSync(serverEnv, readFileSync(serverEnv, 'utf8').trimEnd() + `\nAUDIT_SIGNING_KEY=${randomBytes(32).toString('base64url')}\n`);
  console.log('[setup] added AUDIT_SIGNING_KEY to server/.env');
}

// Upgrade: server/.env files created before PostgreSQL support lack DATABASE_URL.
if (existsSync(serverEnv) && !readVar(serverEnv, 'DATABASE_URL')) {
  writeFileSync(serverEnv, readFileSync(serverEnv, 'utf8').trimEnd() + `\nDATABASE_URL=${DEFAULT_DATABASE_URL}\n`);
  console.log('[setup] added DATABASE_URL to server/.env');
}

if (!existsSync(webhookEnv)) {
  writeFileSync(
    webhookEnv,
    [
      '# Customer webhook / vault runtime (generated by scripts/setup.mjs; do not commit)',
      '# This file belongs to the CUSTOMER trust zone. The encryption key never leaves it.',
      'PORT=4100',
      `WEBHOOK_SIGNING_SECRET=${signing}`,
      '# Old signing secret during a rotation (npm run webhook:rotate-secret); empty otherwise.',
      'WEBHOOK_PREVIOUS_SIGNING_SECRETS=',
      `VAULT_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
      '# env = VAULT_ENCRYPTION_KEY seals credentials; aws-kms / vault-transit = envelope encryption with a KMS (docs/DEPLOYMENT.md)',
      'VAULT_KEY_PROVIDER=env',
      '# Earlier encryption keys during a rotation (npm run vault:rotate-key); empty otherwise.',
      'VAULT_PREVIOUS_ENCRYPTION_KEYS=',
      'WEBHOOK_INSTANCE_ID=whi_local_customer_vault',
      '# Customer-side Postgres (separate database and role from the control plane). Development credentials only.',
      `WEBHOOK_DATABASE_URL=${DEFAULT_WEBHOOK_DATABASE_URL}`,
      '# mock = simulated providers (default). live = call the real provider APIs with the stored credentials.',
      'UPSTREAM_MODE=mock',
      '# Per-application override, e.g. PROVIDER_MODES=github=live,slack=mock',
      'PROVIDER_MODES=',
      '',
    ].join('\n'),
  );
  console.log('[setup] created webhook/.env');
}

// Upgrade: webhook/.env files created before the PostgreSQL credential store lack WEBHOOK_DATABASE_URL.
if (existsSync(webhookEnv) && !readVar(webhookEnv, 'WEBHOOK_DATABASE_URL')) {
  writeFileSync(webhookEnv, readFileSync(webhookEnv, 'utf8').trimEnd() + `\nWEBHOOK_DATABASE_URL=${DEFAULT_WEBHOOK_DATABASE_URL}\n`);
  console.log('[setup] added WEBHOOK_DATABASE_URL to webhook/.env');
}

// Provider CMS: its own database and an Ed25519 key that signs published definitions.
// Consumers (control plane, webhooks) only ever get the public key.
if (!existsSync(cmsEnv)) {
  const pem = generateKeyPairSync('ed25519').privateKey.export({ type: 'pkcs8', format: 'pem' }).toString();
  writeFileSync(
    cmsEnv,
    [
      '# Provider CMS API (generated by scripts/setup.mjs; do not commit)',
      'PORT=4200',
      `CMS_DATABASE_URL=${DEFAULT_CMS_DATABASE_URL}`,
      '# Ed25519 private key that signs published provider definitions (PEM, newlines escaped).',
      `CMS_SIGNING_PRIVATE_KEY=${pem.trim().replace(/\n/g, '\\n')}`,
      '',
    ].join('\n'),
  );
  console.log('[setup] created cms/api/.env');
}

// Token Vault and the customer webhook pull provider definitions from the CMS catalog and
// accept only those signed by the CMS key. Pin its public key in both (upgrade-safe).
const cmsPrivate = readVar(cmsEnv, 'CMS_SIGNING_PRIVATE_KEY');
if (cmsPrivate) {
  const publicPem = createPublicKey(createPrivateKey(cmsPrivate.replace(/\\n/g, '\n'))).export({ type: 'spki', format: 'pem' }).toString();
  const lines = [
    '# Signed provider catalog (provider CMS). Only definitions signed by this key are accepted.',
    'CMS_CATALOG_URL=http://localhost:4200/catalog/v1',
    `CMS_PUBLIC_KEY=${publicPem.trim().replace(/\n/g, '\\n')}`,
  ];
  for (const [file, name] of [[serverEnv, 'server/.env'], [webhookEnv, 'webhook/.env']]) {
    if (existsSync(file) && !readVar(file, 'CMS_PUBLIC_KEY')) {
      writeFileSync(file, readFileSync(file, 'utf8').trimEnd() + '\n' + lines.join('\n') + '\n');
      console.log(`[setup] pinned the CMS public key in ${name}`);
    }
  }
}

// Upgrade: files created before this change point at "localhost". Node may try IPv6 (::1) first,
// which Docker Desktop on Windows accepts and then resets (ECONNRESET). Use the IPv4 address.
for (const [file, name] of [[serverEnv, 'server/.env'], [webhookEnv, 'webhook/.env'], [cmsEnv, 'cms/api/.env']]) {
  if (!existsSync(file)) continue;
  const text = readFileSync(file, 'utf8');
  const next = text.replace(/^((?:WEBHOOK_|CMS_)?DATABASE_URL=postgres(?:ql)?:\/\/[^@\s]*@)localhost(:\d+\/)/gm, '$1127.0.0.1$2');
  if (next !== text) {
    writeFileSync(file, next);
    console.log(`[setup] ${name}: database host localhost -> 127.0.0.1`);
  }
}

// POSTGRES_PORT set: point the local database URLs (127.0.0.1 or localhost) at that port.
if (PG_PORT_SET) {
  for (const [file, name] of [[serverEnv, 'server/.env'], [webhookEnv, 'webhook/.env'], [cmsEnv, 'cms/api/.env']]) {
    if (!existsSync(file)) continue;
    const text = readFileSync(file, 'utf8');
    const next = text.replace(/^((?:WEBHOOK_|CMS_)?DATABASE_URL=postgres(?:ql)?:\/\/[^@\s]*@(?:127\.0\.0\.1|localhost):)\d+(\/)/gm, `$1${PG_PORT}$2`);
    if (next !== text) {
      writeFileSync(file, next);
      console.log(`[setup] ${name}: database port ${PG_PORT} (POSTGRES_PORT)`);
    }
  }
}
